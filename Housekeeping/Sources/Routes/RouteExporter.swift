// Housekeeping — Route Exporter
//
// Generates clean Markdown, CSV, and Plain Text export reports from RouteSweep results
// and handles saving to files or copying to the system pasteboard.

import Foundation
import AppKit
import UniformTypeIdentifiers

struct RouteExporter {
    static func dateStamp() -> String {
        let formatter = DateFormatter()
        formatter.dateFormat = "yyyy-MM-dd_HHmm"
        return formatter.string(from: Date())
    }

    static func generateMarkdown(results: [RouteResult], provider: ProviderKind, baseline: BaselineSample?) -> String {
        var md = "# Route Sweep Report\n\n"
        md += "- **Date**: \(Date().formatted(date: .abbreviated, time: .standard))\n"
        md += "- **Provider**: \(provider.displayName)\n"
        md += "- **Total Routes Tested**: \(results.count)\n"
        let working = results.filter { $0.verdict != .failed }
        md += "- **Working Routes**: \(working.count) of \(results.count)\n"
        if let baseline = baseline, let ping = baseline.pingMs {
            md += "- **Baseline Direct Ping**: \(Int(ping)) ms\n"
        }
        if let best = results.filter({ $0.verdict != .failed }).min(by: { $0.score < $1.score }) {
            let loc = [best.target.location.city, best.target.location.country].filter { !$0.isEmpty }.joined(separator: ", ")
            md += "- **Best Route**: **\(best.target.routeLabel)** (\(loc)) — Ping: \(Int(best.pingMs ?? 0)) ms, Connect: \(String(format: "%.1fs", best.connectSeconds ?? 0))\n"
        }
        md += "\n---\n\n"
        md += "## Detailed Route Performance\n\n"
        md += "| Status | Location | Protocol | Ping | Connect | Page Fetch | Packet Loss | Exit IP / Diagnostics |\n"
        md += "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n"

        let sorted = results.sorted { $0.score < $1.score }
        for r in sorted {
            let loc = [r.target.location.city, r.target.location.country].filter { !$0.isEmpty }.joined(separator: ", ")
            let status = r.verdict.title
            let proto = r.target.routeLabel
            let ping = r.pingMs.map { "\(Int($0)) ms" } ?? "—"
            let connect = r.connectSeconds.map { String(format: "%.1fs", $0) } ?? "—"
            let fetch = r.fetchSeconds.map { String(format: "%.1fs", $0) } ?? "—"
            let loss = r.packetLoss.map { "\(Int($0 * 100))%" } ?? "0%"
            let info = r.exitIP ?? (r.failureReason ?? "—")
            md += "| \(status) | \(loc) | \(proto) | \(ping) | \(connect) | \(fetch) | \(loss) | \(info) |\n"
        }

        md += "\n\n*Generated by Housekeeper — Made by Morad*\n"
        return md
    }

    static func generateCSV(results: [RouteResult], provider: ProviderKind) -> String {
        var csv = "Status,Route,City,Country,Node,Protocol,PingMs,ConnectSec,FetchSec,PacketLossPct,ExitIP,FailureReason\n"
        let sorted = results.sorted { $0.score < $1.score }
        for r in sorted {
            let status = r.verdict.title
            let route = r.target.routeLabel.replacingOccurrences(of: ",", with: " ")
            let city = r.target.location.city.replacingOccurrences(of: ",", with: " ")
            let country = r.target.location.country.replacingOccurrences(of: ",", with: " ")
            let node = r.target.location.node.replacingOccurrences(of: ",", with: " ")
            let proto = r.target.routeLabel
            let ping = r.pingMs.map { String(format: "%.1f", $0) } ?? ""
            let connect = r.connectSeconds.map { String(format: "%.2f", $0) } ?? ""
            let fetch = r.fetchSeconds.map { String(format: "%.2f", $0) } ?? ""
            let loss = r.packetLoss.map { String(format: "%.1f", $0 * 100) } ?? "0"
            let ip = r.exitIP ?? ""
            let fail = (r.failureReason ?? "").replacingOccurrences(of: ",", with: " ").replacingOccurrences(of: "\n", with: " ")
            csv += "\(status),\(route),\(city),\(country),\(node),\(proto),\(ping),\(connect),\(fetch),\(loss),\(ip),\"\(fail)\"\n"
        }
        return csv
    }

    static func generateText(results: [RouteResult], provider: ProviderKind) -> String {
        var txt = "HOUSEKEEPER ROUTE SWEEP REPORT\n"
        txt += "================================================================================\n"
        txt += "Date: \(Date().formatted(date: .abbreviated, time: .standard))\n"
        txt += "Provider: \(provider.displayName)\n"
        txt += "Total Routes Tested: \(results.count)\n"
        let working = results.filter { $0.verdict != .failed }
        txt += "Working Routes: \(working.count) / \(results.count)\n"
        txt += "================================================================================\n\n"

        let sorted = results.sorted { $0.score < $1.score }
        for (i, r) in sorted.enumerated() {
            let loc = [r.target.location.city, r.target.location.country].filter { !$0.isEmpty }.joined(separator: ", ")
            txt += String(format: "%2d. [%@] %@ — %@ (%@)\n", i + 1, r.verdict.title.uppercased(), r.target.routeLabel, loc, r.target.routeLabel)
            txt += "    Ping: \(r.pingMs.map { "\(Int($0)) ms" } ?? "—") | Connect: \(r.connectSeconds.map { String(format: "%.1fs", $0) } ?? "—") | Fetch: \(r.fetchSeconds.map { String(format: "%.1fs", $0) } ?? "—") | Loss: \(r.packetLoss.map { "\(Int($0 * 100))%" } ?? "0%")\n"
            if let ip = r.exitIP {
                txt += "    Exit IP: \(ip)\n"
            }
            if let fail = r.failureReason, !fail.isEmpty {
                txt += "    Note: \(fail)\n"
            }
            txt += "\n"
        }

        txt += "================================================================================\n"
        txt += "Generated by Housekeeper — Made by Morad\n"
        return txt
    }

    @MainActor
    static func saveFile(content: String, defaultName: String, extensionType: String) {
        let savePanel = NSSavePanel()
        savePanel.title = "Save Route Sweep Results"
        savePanel.nameFieldStringValue = defaultName
        savePanel.allowedContentTypes = [UTType(filenameExtension: extensionType) ?? .plainText]
        savePanel.canCreateDirectories = true
        if savePanel.runModal() == .OK, let url = savePanel.url {
            try? content.write(to: url, atomically: true, encoding: .utf8)
        }
    }
}
